#!/usr/bin/env python3
"""Writes the generated parts of App/Sources/DesignSystem/Tokens.swift from Packages/design-tokens/tokens.json.
Usage: scripts/gen_tokens.py [--check]   (--check: fail if Tokens.swift is out of date; run by scripts/test.sh core)"""
import json, pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
tokens = json.loads((root / "Packages/design-tokens/tokens.json").read_text())
swift = root / "App/Sources/DesignSystem/Tokens.swift"

def hx(v):
    assert re.fullmatch(r"#[0-9A-Fa-f]{6}", v), f"bad colour {v}"
    return "0x" + v[1:].upper()

def palette(ind):
    out = []
    for name, c in tokens["color"].items():
        if "note" in c: out.append(f"{ind}/// {c['note']}")
        if "value" in c: out.append(f"{ind}static let {name} = Color(hex: {hx(c['value'])})")
        else:
            alpha = f", alpha: {c['alpha']}" if "alpha" in c else ""
            out.append(f"{ind}static let {name} = dynamic(light: {hx(c['light'])}, dark: {hx(c['dark'])}{alpha})")
    return out

def layout(ind):
    row = lambda d: ", ".join(f"{k}: CGFloat = {v}" for k, v in d.items())
    return [f"{ind}enum Space {{", f"{ind}    static let {row(tokens['space'])}", f"{ind}}}",
            f"{ind}enum Radius {{", f"{ind}    static let {row(tokens['radius'])}", f"{ind}}}"]

src = swift.read_text(); new = src
for region, make in (("palette", palette), ("layout", layout)):
    m = re.search(rf"^( *)// BEGIN GENERATED {region}.*?\n(.*?)^ *// END GENERATED {region}\n", new, re.S | re.M)
    assert m, f"markers for {region} missing in Tokens.swift"
    ind = m.group(1)
    body = "\n".join(make(ind)) + "\n"
    new = new[:m.start(2)] + body + new[m.end(2):]
def css():
    def rgba(v, a): return f"rgba({int(v[1:3],16)}, {int(v[3:5],16)}, {int(v[5:7],16)}, {a})" if a is not None else v
    kebab = lambda n: re.sub(r"(?<!^)(?=[A-Z])", "-", n).lower()
    light, dark = [], []
    for n, c in tokens["color"].items():
        if "value" in c: light.append(f"  --{kebab(n)}: {c['value']};"); continue
        light.append(f"  --{kebab(n)}: {rgba(c['light'], c.get('alpha'))};"); dark.append(f"  --{kebab(n)}: {rgba(c['dark'], c.get('alpha'))};")
    light += [f"  --space-{k}: {v}px;" for k, v in tokens["space"].items()] + [f"  --radius-{k}: {v}px;" for k, v in tokens["radius"].items()]
    return ("/* Generated by scripts/gen_tokens.py from Packages/design-tokens/tokens.json; do not edit. */\n"
            ":root, [data-theme=\"light\"] {\n" + "\n".join(light) + "\n}\n[data-theme=\"dark\"] {\n" + "\n".join(dark) + "\n}\n")

outputs = {swift: (src, new)}
css_path = root / "Packages/design-tokens/tokens.css"
outputs[css_path] = (css_path.read_text() if css_path.exists() else "", css())
if "--check" in sys.argv:
    stale = [str(p.relative_to(root)) for p, (old, fresh) in outputs.items() if old != fresh]
    if stale: print(f"tokens: out of date: {', '.join(stale)}; run scripts/gen_tokens.py"); sys.exit(1)
    print("tokens: Tokens.swift and tokens.css match tokens.json")
else:
    for p, (_, fresh) in outputs.items(): p.write_text(fresh)
    print("tokens: wrote Tokens.swift and tokens.css")
